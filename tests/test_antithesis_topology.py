@pytest.mark.parametrize('damage', ['missing-hostname', 'cycle', 'unknown-volume', 'disconnected-peer'])
def test_broken_source_contract_is_reported_as_unavailable(asset_copy, damage):
    import yaml
    path = asset_copy / 'docker-compose.yaml'
    compose = yaml.safe_load(path.read_text())
    if damage == 'missing-hostname':
        del compose['services']['tracer']['hostname']
    elif damage == 'cycle':
        compose['services']['tracer']['depends_on'] = {'tracer-sidecar': {'condition': 'service_started'}}
    elif damage == 'unknown-volume':
        compose['services']['tracer']['volumes'].append('undeclared:/unknown')
    else:
        compose['services']['relay1']['networks'] = {'amaru-consumer-net': None}
    path.write_text(yaml.safe_dump(compose))
    catalog = backend().topology_catalog(state_dir=asset_copy / 'saved')
    assert not any(template['available'] for template in catalog['templates'])


