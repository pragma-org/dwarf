def test_corrupt_saved_configuration_is_visible_in_catalog(tmp_path):
    plan = backend().resolve_topology(request())
    record = backend().save_configuration(request(), plan['topology_digest'], state_dir=tmp_path)
    (tmp_path / (record['id'] + '.json')).write_text('{broken')
    catalog = backend().topology_catalog(state_dir=tmp_path)
    assert not catalog['configurations']
    assert catalog['issues'][0]['configuration_id'] == record['id']


def test_save_reload_is_atomic_idempotent_and_separate_from_local(tmp_path):
    plan = backend().resolve_topology(request())
    def save(_):
        return backend().save_configuration(request(), plan['topology_digest'], state_dir=tmp_path)
    with ThreadPoolExecutor(max_workers=4) as executor:
        records = list(executor.map(save, range(8)))
    assert len({record['id'] for record in records}) == 1
    assert len(list(tmp_path.glob('*.json'))) == 1
    record = records[0]
    resolved = backend().resolve_topology({'source': 'saved', 'configuration_id': record['id']}, state_dir=tmp_path)
    assert resolved['topology_digest'] == plan['topology_digest']
    assert resolved['graph'] == plan['graph']


def test_stale_save_and_stale_saved_revision_are_rejected(tmp_path, asset_copy):
    plan = backend().resolve_topology(request())
    record = backend().save_configuration(request(), plan['topology_digest'], state_dir=tmp_path)
    file = asset_copy / 'tracer-config.yaml'
    file.write_text(file.read_text() + '\n# change\n')
    with pytest.raises(backend().TopologyError) as error:
        backend().save_configuration(request(), plan['topology_digest'], state_dir=tmp_path)
    assert error.value.status == 409
    resolved = backend().resolve_topology({'source': 'saved', 'configuration_id': record['id']}, state_dir=tmp_path)
    assert resolved['state'] == 'stale'
    assert resolved['execution_ready'] is False


def test_api_limits_methods_payload_and_save_authentication(tmp_path, monkeypatch):
    from profile_manager.data import antithesis_topology as api
    monkeypatch.setattr(api, 'state_directory', lambda: tmp_path)
    def call(path, value=None, method='POST', raw=None):
        status, _, body = api.dispatch_topology_request(method=method, path='/api/antithesis-run/topology/' + path,
            body=raw if raw is not None else json.dumps(value).encode(), expected_token='secret')
        return status, json.loads(body)
    assert call('resolve', method='GET')[0] == 405
    assert call('resolve', raw=b'[')[0] == 400
    assert call('resolve', raw=b'x' * 8193)[0] == 413
    assert call('resolve', [1, 2])[0] == 400
    status, payload = call('resolve', request())
    assert status == 200 and payload['topology']['state'] == 'resolved'
    save = {'request': request(), 'topology_digest': payload['topology']['topology_digest']}
    assert call('configurations', save)[0] == 403
    assert call('configurations', {**save, 'token': 'wrong'})[0] == 403
    assert not list(tmp_path.glob('*.json'))
    assert call('configurations', {**save, 'token': 'secret'})[0] == 200
    status, catalog = call('catalog', method='GET')
    assert status == 200 and len(catalog['configurations']) == 1
