import json
import shutil
from concurrent.futures import ThreadPoolExecutor

import pytest


def backend():
    from profile_manager import antithesis_topology
    return antithesis_topology


def request(kind='amaru'):
    return {'source': 'new', 'name': 'Remote control', 'template_id': f'{kind}-control-v1',
            'cardano_count': 0 if kind == 'amaru' else 2,
            'amaru_count': 0 if kind == 'cardano' else 2, 'network_magic': 42}


@pytest.mark.parametrize('kind,targets,total', [
    ('cardano', {'relay1', 'relay2'}, 9),
    ('amaru', {'amaru-relay-1', 'amaru-relay-2'}, 14),
    ('mixed', {'relay1', 'relay2', 'amaru-relay-1', 'amaru-relay-2'}, 14),
])
def test_compiles_exact_remote_service_graph(kind, targets, total):
    result = backend().resolve_topology(request(kind))
    assert result['state'] == 'resolved'
    assert result['execution_ready'] is False
    graph = result['graph']
    assert {s['id'] for s in graph['services'] if s['role'] == 'target'} == targets
    assert len(graph['services']) == total
    names = {s['id'] for s in graph['services']}
    assert not names & {'dwarf-adversary', 'decoder-fuzz', 'tx-generator', 'asteria-game', 'workload'}
    assert {'p1', 'p2', 'p3'} <= names - targets
    assert all(edge['from'] in names and edge['to'] in names for edge in graph['peers'])
    assert all(set(s['depends_on']) <= names for s in graph['services'])
    assert any(e['from'] == 'relay1' and e['to'] == 'p3' for e in graph['peers'])
    assert result['pending_bindings']
    assert graph['generated_peer_inputs']  # Do not invent the configurator's generated bytes.


